fn ensure_icon() {
    let manifest_dir = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR missing"),
    );
    let icon_dir = manifest_dir.join("icons");
    let icon = icon_dir.join("icon.png");
    fs::create_dir_all(&icon_dir).expect("failed to create Tauri icon directory");
    let current = fs::read(&icon).ok();
    if current.as_deref() != Some(ARCZ_ICON_PNG) {
        fs::write(&icon, ARCZ_ICON_PNG).expect("failed to materialize deterministic ARCZ icon");
    }
}

fn main() {
    ensure_icon();
    tauri_build::build();
}
